#!/usr/bin/env python3
"""Generate Android vectors from the SVG sources in the iOS asset catalog."""

from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "ios/Tidemeld/Resources/Assets.xcassets"
DRAWABLES = ROOT / "app/src/main/res/drawable"

for asset in sorted(ASSETS.glob("Platform*.imageset/*.svg")):
    svg = ET.parse(asset).getroot()
    assert svg.attrib["viewBox"] == "0 0 24 24"
    paths = svg.findall("{http://www.w3.org/2000/svg}path")
    assert paths and all(set(path.attrib) == {"d"} for path in paths)
    content = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tools/sync-platform-icons.py. Simple Icons, CC0-1.0. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24">',
    ]
    for path in paths:
        content.append(f'    <path android:fillColor="#FF000000" android:pathData="{path.attrib["d"]}" />')
    content.append("</vector>")
    (DRAWABLES / f"ic_platform_{asset.stem}.xml").write_text("\n".join(content) + "\n")
